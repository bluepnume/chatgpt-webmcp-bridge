// Bundles the panel's code (src/panel.ts, with glottis) into one script and
// writes it to src/panel-script.generated.ts as a string, which
// src/panel-html.ts places inline in the panel's HTML. The server can then
// hand ChatGPT the whole panel without serving or loading any other file.
//
// Run before type-checking, testing or building: npm run build:panel.

import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');

const result = await build({
    entryPoints:   [ path.join(root, 'src/panel.ts') ],
    bundle:        true,
    format:        'iife',
    platform:      'browser',
    target:        'es2022',
    minify:        true,
    write:         false,
    legalComments: 'none'
});

const [ output ] = result.outputFiles;

if (!output) {
    throw new Error('esbuild produced no panel bundle');
}

// The script sits inside <script>…</script>, which a literal "</script" in
// the code would end early.
const script = output.text.replaceAll('</script', String.raw`<\/script`);

// Written as a template literal, which the lint rules accept on a long line.
// Escaped so it holds exactly the script: backslashes, backticks, `${` and
// carriage returns (which a template literal would turn into newlines).
const literal = script
    .replaceAll('\\', '\\\\')
    .replaceAll('`', '\\`')
    .replaceAll('${', '\\${')
    .replaceAll('\r', String.raw`\r`);

await writeFile(
    path.join(root, 'src/panel-script.generated.ts'),
    `// Generated by scripts/build-panel.ts from src/panel.ts. Do not edit.\n\nexport const PANEL_SCRIPT = \`${ literal }\`;\n`
);

console.log(`panel script: ${ (script.length / 1024).toFixed(1) } KiB`);
